#!/usr/bin/env python3
"""Generate each smabo repository's copy of the protocol from protocol.json.

protocol.json (topic tables, protocol number) and face_schema.json (the face
expression schema smabo-app serves and smabo-sim mirrors) are the single source
of truth. This script writes, into the sibling checkouts next to this one:

  smabo-brain/brain/protocol_gen.py            tables for brain/topics.py (and smabo-brain-ros)
  smabo-web/src/ws/protocol.gen.ts             smabo-web's tables
  smabo-app/lib/core/wire/protocol.g.dart      smabo-app's tables
  smabo-esp32/protocol_gen.py                  the ESP32's tables
  smabo-sim/smabo_sim/protocol_gen.py          the simulated ESP32's and phone's tables
  smabo-app/test/face_schema.json              face schema (smabo-app's tests)
  smabo-sim/tests/face_schema.json             face schema (smabo-sim's tests)
  TOPICS.md                                    the topic table, for people

Usage:
  python3 gen.py            write every file whose repository is checked out
  python3 gen.py --check    exit 1 and list the files that are out of date

Run it after editing protocol.json (bump "protocol" when a topic is renamed or
removed, or a message changes type or meaning), then commit the generated
files in each repository.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPOS = HERE.parent
HEADER = "GENERATED by smabo-protocol/gen.py from protocol.json. Do not edit; run gen.py."

P = json.loads((HERE / "protocol.json").read_text(encoding="utf-8"))
FACE_SCHEMA = (HERE / "face_schema.json").read_text(encoding="utf-8")
TYPES: dict[str, str] = P["types"]


def table(role: str, kind: str) -> list[tuple[str, str]]:
    return [(t, TYPES[t]) for t in P[kind][role]]


def py_dict(rows: list[tuple[str, str]], indent: str) -> str:
    w = max((len(t) for t, _ in rows), default=0) + 3
    return "".join(f'{indent}{(chr(34) + t + chr(34) + ":").ljust(w)} "{ty}",\n' for t, ty in rows)


def py_tuple(rows: list[tuple[str, str]], prefix: str = "") -> str:
    w = max((len(prefix + t) for t, _ in rows), default=0) + 3
    return "".join(f'    ({(chr(34) + prefix + t + chr(34) + ",").ljust(w)} "{ty}"),\n' for t, ty in rows)


# ── smabo-brain ─────────────────────────────────────────────────────────────
def brain() -> str:
    out = [f'"""{HEADER}\n\nImported by brain/topics.py; see there for what the tables mean.\n"""\n\n',
           f'PROTOCOL_VERSION = {P["protocol"]}\n\n',
           "SOURCE_PREFIXES: dict[str, str] = {\n",
           *(f'    "{r}": "{p}",\n' for r, p in P["source_prefixes"].items()), "}\n\n"]
    for kind in ("publish", "subscribe"):
        out.append(f"{kind.upper()}: dict[str, dict[str, str]] = {{\n")
        for role in P[kind]:
            out.append(f'    "{role}": {{\n{py_dict(table(role, kind), "        ")}    }},\n')
        out.append("}\n\n")
    for key in ("ros_only_topics", "app_topics", "from_brain"):
        items = ", ".join(f'"{t}"' for t in P[key])
        out.append(f"{key.upper()}: frozenset[str] = frozenset({{{items}}})\n")
    return "".join(out)


# ── smabo-web ───────────────────────────────────────────────────────────────
def web() -> str:
    def ts(rows):
        w = max(len(t) for t, _ in rows) + 3
        return "".join(f"  {(chr(39) + t + chr(39) + ':').ljust(w)} '{ty}',\n" for t, ty in rows)
    ros_only = set(P["ros_only_topics"])
    pub = [r for r in table("web", "publish") if r[0] not in ros_only]
    return (f"// {HEADER}\n"
            "// smabo-web's side of the brain protocol (smabo-brain / smabo-brain-ros).\n\n"
            f"export const PROTOCOL_VERSION = {P['protocol']};\n"
            f"export const SOURCE_PREFIX = '{P['source_prefixes']['web']}';\n\n"
            "/** Canonical topics published over the brain socket (sent as /web<topic>).\n"
            " *  Navigation topics go over roslib to smabo-brain-ros instead. */\n"
            f"export const PUBLISH: Record<string, string> = {{\n{ts(pub)}}};\n\n"
            "/** Canonical topics read from the brain. */\n"
            f"export const SUBSCRIBE: Record<string, string> = {{\n{ts(table('web', 'subscribe'))}}};\n")


# ── smabo-app ───────────────────────────────────────────────────────────────
def app() -> str:
    def dart(rows):
        return "".join(f"    '{t}': '{ty}',\n" for t, ty in rows)
    return (f"// {HEADER}\n\n"
            "/// smabo-app's side of the brain protocol (see ros_compat.dart).\n"
            "class ProtocolTables {\n"
            f"  static const version = {P['protocol']};\n"
            f"  static const sourcePrefix = '{P['source_prefixes']['app']}';\n\n"
            "  /// Canonical topics the app publishes (sent as `/app<topic>`), with types.\n"
            f"  static const publish = <String, String>{{\n{dart(table('app', 'publish'))}  }};\n\n"
            "  /// Canonical topics the app reads, with types.\n"
            f"  static const subscribe = <String, String>{{\n{dart(table('app', 'subscribe'))}  }};\n"
            "}\n")


# ── smabo-esp32 / smabo-sim ────────────────────────────────────────────────
def esp32() -> str:
    pre = P["source_prefixes"]["esp32"]
    return (f'"""{HEADER}\n\nImported by brain_link.py."""\n\n'
            f"PROTOCOL_VERSION = {P['protocol']}\n"
            f'SOURCE_PREFIX = "{pre}"\n\n'
            f"ADVERTISE = (\n{py_tuple(table('esp32', 'publish'), pre)})\n"
            f"SUBSCRIBE = (\n{py_tuple(table('esp32', 'subscribe'))})\n")


def sim() -> str:
    out = [f'"""{HEADER}\n\nImported by smabo_sim/protocol.py."""\n\n',
           f"PROTOCOL_VERSION = {P['protocol']}\n"]
    for role, name in (("esp32", "ESP32"), ("app", "APP")):
        pre = P["source_prefixes"][role]
        out.append(f'\n{name}_PREFIX = "{pre}"\n'
                   f"{name}_ADVERTISE = (\n{py_tuple(table(role, 'publish'), pre)})\n"
                   f"{name}_SUBSCRIBE = (\n{py_tuple(table(role, 'subscribe'))})\n")
    return "".join(out)


# ── people ─────────────────────────────────────────────────────────────────
def topics_md() -> str:
    roles = list(P["source_prefixes"])
    rows = []
    for t, ty in TYPES.items():
        senders = [r for r in roles if t in P["publish"][r]] or (["brain"] if t in P["from_brain"] else [])
        readers = [r for r in roles if t in P["subscribe"][r]] + (["brain"] if t in P["to_brain"] else [])
        rows.append(f"| `{t}` | `{ty}` | {', '.join(senders) or '-'} | {', '.join(readers) or '-'} "
                    f"| {P['notes'].get(t, '')} |")
    prefixes = ", ".join(f"{r} `{p}`" for r, p in P["source_prefixes"].items())
    return (f"<!-- {HEADER} -->\n\n# smabo のトピック表（プロトコル {P['protocol']}）\n\n"
            f"送るときは送信元 prefix（{prefixes}）を付け、brain が外して正式名で配ります。\n"
            "「brain」は brain 自身が作って送る、または brain が受け取って使うトピックです。"
            "smabo-brain-ros のみのトピックは smabo-brain では捨てられます。\n\n"
            "| トピック | 型 | 送る | 受け取る | 説明 |\n|---|---|---|---|---|\n"
            + "\n".join(rows) + "\n")


OUTPUTS = {
    "smabo-brain/brain/protocol_gen.py": brain,
    "smabo-web/src/ws/protocol.gen.ts": web,
    "smabo-app/lib/core/wire/protocol.g.dart": app,
    "smabo-esp32/protocol_gen.py": esp32,
    "smabo-sim/smabo_sim/protocol_gen.py": sim,
    "smabo-app/test/face_schema.json": lambda: FACE_SCHEMA,
    "smabo-sim/tests/face_schema.json": lambda: FACE_SCHEMA,
    "smabo-protocol/TOPICS.md": topics_md,
}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for rel, make in OUTPUTS.items():
        path = REPOS / rel
        if not path.parent.exists():          # that repository is not checked out
            print(f"skip  {rel}")
            continue
        text = make()
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            stale.append(rel)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    if stale:
        print("out of date (run smabo-protocol/gen.py):\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
